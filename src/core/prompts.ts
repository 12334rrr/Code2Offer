export interface Stage2BatchInput {
  knowledgeDigest: string;
  cardsText: string;
  slots: Array<{ index: number; category: string; difficulty: string; target: string; hint: string; requireComparison: boolean }>;
  fileList: string[];
  askedStems: string[];
}

export function stage2BatchUser(input: Stage2BatchInput): string {
  return `# 项目知识卡摘要
${input.knowledgeDigest}

# 相关模块理解卡
${input.cardsText}

# 可引用的文件清单(代码依据只能从这里选,行号范围 1-端)
${input.fileList.join('\n')}

# 已出题目(禁止重复)
${input.askedStems.length ? input.askedStems.map((s) => '- ' + s).join('\n') : '(暂无)'}

# 本次题位(共 ${input.slots.length} 题,必须全部完成,category/difficulty/target 原样返回)
${input.slots
  .map(
    (s) =>
      `${s.index}. 类别=${s.category} | 难度=${s.difficulty} | 目标=${s.target} | 出题引导=${s.hint}${s.requireComparison ? ' | 必须含对比块' : ''}`
  )
  .join('\n')}

请输出 {"questions":[...]} JSON,数量与题位数一致、顺序一致。`;
}

